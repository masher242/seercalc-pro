#!/usr/bin/env python3
"""Refresh src/data/climateCdd.json: cooling degree days for every place we price AC in.

One climate measure for every region, so cooling hours (and the "compare anywhere"
figures) are worked out the same way in the U.S., Canada, the Caribbean and Europe.

Source: Open-Meteo historical weather API (ERA5 reanalysis, Copernicus/ECMWF), free,
no key. For each place in src/data/climateLocations.json: geocode (Open-Meteo
geocoding), fetch daily mean temperature for the last 10 full years, and compute
cooling degree days at base 18.3 °C (65 °F, the U.S. standard):
    CDD = sum over days of max(0, daily mean - 18.3)
averaged per year.

    python3 scripts/update-climate.py              # last 10 full years
    python3 scripts/update-climate.py --years 10
"""
from __future__ import annotations

import argparse
import datetime as dt
import json
import time
import urllib.parse
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LOCS = ROOT / "src" / "data" / "climateLocations.json"
OUT = ROOT / "src" / "data" / "climateCdd.json"
BASE_C = 18.3
GEO = "https://geocoding-api.open-meteo.com/v1/search"
ARCHIVE = "https://archive-api.open-meteo.com/v1/archive"
UA = {"User-Agent": "airconditionanswers-climate/1.0"}


def get(url: str, params: dict) -> dict:
    req = urllib.request.Request(f"{url}?{urllib.parse.urlencode(params)}", headers=UA)
    for attempt in range(4):
        try:
            with urllib.request.urlopen(req, timeout=90) as r:
                return json.load(r)
        except Exception:  # noqa: BLE001 — retry transient errors / rate limits
            if attempt == 3:
                raise
            time.sleep(10 * (attempt + 1))
    raise RuntimeError("unreachable")


def geocode(loc: dict) -> dict:
    res = get(GEO, {"name": loc.get("query", loc["name"]), "count": 20, "countryCode": loc["country"], "language": "en"})
    hits = res.get("results") or []
    if loc.get("admin1"):
        hits = [h for h in hits if h.get("admin1") == loc["admin1"]] or hits
    if not hits:
        raise SystemExit(f"Can't geocode {loc['id']}")
    h = max(hits[:5], key=lambda x: x.get("population") or 0) if not loc.get("admin1") else hits[0]
    return {"lat": round(h["latitude"], 3), "lon": round(h["longitude"], 3), "found": f"{h['name']}, {h.get('admin1', '')}, {h.get('country_code', '')}"}


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--years", type=int, default=10)
    args = ap.parse_args()

    end_year = dt.date.today().year - 1
    start_year = end_year - args.years + 1
    locs = json.loads(LOCS.read_text(encoding="utf-8"))["locations"]
    out = {}
    for loc in locs:
        g = geocode(loc) if "lat" not in loc else {"lat": loc["lat"], "lon": loc["lon"], "found": loc["name"]}
        data = get(ARCHIVE, {
            "latitude": g["lat"], "longitude": g["lon"],
            "start_date": f"{start_year}-01-01", "end_date": f"{end_year}-12-31",
            "daily": "temperature_2m_mean", "timezone": "auto",
        })
        days, temps = data["daily"]["time"], data["daily"]["temperature_2m_mean"]
        per_year: dict[int, float] = {}
        for d, t in zip(days, temps):
            if t is not None:
                per_year[int(d[:4])] = per_year.get(int(d[:4]), 0.0) + max(0.0, t - BASE_C)
        cdd = sum(per_year.values()) / len(per_year)
        out[loc["id"]] = {"name": loc["name"], "found": g["found"], "lat": g["lat"], "lon": g["lon"], "cdd": round(cdd)}
        time.sleep(0.5)

    OUT.write_text(json.dumps({
        "_readme": "Cooling degree days (base 18.3 °C / 65 °F) per place, yearly average. Generated by scripts/update-climate.py from Open-Meteo (ERA5). Used to estimate cooling hours on every AC cost page.",
        "source": "Open-Meteo historical weather API (ERA5 reanalysis, Copernicus/ECMWF)",
        "sourceUrl": "https://open-meteo.com/en/docs/historical-weather-api",
        "baseC": BASE_C,
        "years": f"{start_year}–{end_year}",
        "updated": dt.date.today().isoformat(),
        "locations": out,
    }, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"Cooling degree days for {len(out)} places ({start_year}-{end_year})")


if __name__ == "__main__":
    main()
